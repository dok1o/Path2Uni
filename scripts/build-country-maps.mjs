// Keep everything after the catalogue literal untouched: the projection helpers and the
// mapCache live there, and slicing from getCountryMap once dropped them and broke the map.
const tail = readFileSync(new URL('../src/data/countryMaps.js', import.meta.url), 'utf8')
const catalogEnd = tail.indexOf('\n]\n') >= 0 ? tail.indexOf('\n]\n') + 3 : tail.indexOf('export function getCountryMap')
const after = tail.slice(catalogEnd)

writeFileSync(new URL('../src/data/countryMaps.js', import.meta.url),
  `${header}${JSON.stringify(catalog, null, 2)}\n\n${after}`)

console.log(`${catalog.length} countries, ${catalog.reduce((n, c) => n + c.cities.length, 0)} cities, ` +
  `${catalog.reduce((n, c) => n + c.cities.reduce((m, city) => m + city.universities.length, 0), 0)} universities`)
