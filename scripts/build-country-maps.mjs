// Regenerates src/data/countryMaps.js from the curated catalogue.
//
// The teammates hand-wrote each country's cities and universities, and gave every entry a
// "88% match" figure that is not computed from anything. A student reads that as an estimate
// of their chances. This replaces those lists with the catalogue's real cities, coordinates
// and taught subjects, and drops the invented number.
//
// The file's shape is unchanged, so CountryMap3D and UniversityExplorer keep working as-is.
// Run: npm run catalog:maps

import { writeFileSync, readFileSync } from 'node:fs'
import { universities, cities, countries, FIELD_LABELS, cityById } from '../src/data/worldUniversities.js'

// ne-50m holds map *units*, so there is no United Kingdom outline — England and Scotland are
// separate. The picker says "England", so the map carries English cities only; Edinburgh,
// Glasgow and St Andrews stay in the catalogue for shortlists but are not plotted here.
const SCOTLAND = new Set(['edinburgh', 'glasgow', 'st-andrews'])

const COUNTRY_META = {
  us: { id: 'usa', name: 'United States', shortName: 'USA', geoUnit: 'USA', currency: '$' },
  it: { id: 'italy', name: 'Italy', shortName: 'Italy', geoUnit: 'ITA', currency: '€' },
  gb: { id: 'england', name: 'England', shortName: 'England', geoUnit: 'ENG', currency: '£' },
  hu: { id: 'hungary', name: 'Hungary', shortName: 'Hungary', geoUnit: 'HUN', currency: 'Ft' },
  cn: { id: 'china', name: 'China', shortName: 'China', geoUnit: 'CHN', currency: '¥' },
  ae: { id: 'uae', name: 'United Arab Emirates', shortName: 'UAE', geoUnit: 'ARE', currency: 'AED' },
  my: { id: 'malaysia', name: 'Malaysia', shortName: 'Malaysia', geoUnit: 'MYS', currency: 'RM' },
  ch: { id: 'switzerland', name: 'Switzerland', shortName: 'Switzerland', geoUnit: 'CHE', currency: 'CHF' },
  nl: { id: 'netherlands', name: 'Netherlands', shortName: 'Netherlands', geoUnit: 'NLD', currency: '€' },
  de: { id: 'germany', name: 'Germany', shortName: 'Germany', geoUnit: 'DEU', currency: '€' },
}

// The teammates' city notes are good copy; keep the ones that still apply.
const KEPT_NOTES = {
  milan: 'Design, engineering & business', bologna: 'Historic student city',
  rome: 'Culture, research & opportunity', turin: 'Innovation and technology',
  florence: 'Arts, architecture & humanities', boston: 'Research, biotech & liberal arts',
  'new-york': 'Finance, media & global networks', chicago: 'Economics, research & city life',
  'los-angeles': 'Film, tech & entrepreneurship', london: 'Global careers, finance & creativity',
  oxford: 'Tutorial teaching & research', cambridge: 'Science, technology & tradition',
}

/** A city's note, from the kept copy or from what its universities actually teach. */
function noteFor(city, list) {
  if (KEPT_NOTES[city.id]) return KEPT_NOTES[city.id]
  const counts = new Map()
  for (const uni of list) for (const field of uni.fields) counts.set(field, (counts.get(field) ?? 0) + 1)
  const top = [...counts.entries()].sort((a, b) => b[1] - a[1]).slice(0, 3).map(([field]) => FIELD_LABELS[field])
  return top.join(' · ')
}

const catalog = []
for (const country of countries) {
  const meta = COUNTRY_META[country.iso]
  if (!meta) continue
  const list = cities
    .filter(city => city.country === country.iso)
    .filter(city => !(country.iso === 'gb' && SCOTLAND.has(city.id)))
    .map(city => {
      const here = universities.filter(uni => uni.city === city.id)
      return {
        name: city.name,
        coordinates: [city.lng, city.lat],
        note: noteFor(city, here),
        universities: here.map(uni => ({
          id: uni.id,
          name: uni.name,
          // What it teaches, not an invented percentage.
          focus: uni.fields.slice(0, 2).map(field => FIELD_LABELS[field]).join(' · '),
          levels: uni.levels,
          web: uni.web,
        })),
      }
    })
    .filter(city => city.universities.length > 0)
    .sort((a, b) => b.universities.length - a.universities.length)
  catalog.push({ ...meta, cities: list })
}

